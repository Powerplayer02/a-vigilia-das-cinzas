"""Portas de gameplay com dados independentes da engine."""

from typing import Protocol, Sequence, runtime_checkable
from collections.abc import Callable

from vigilia.core.mathx import Vec3
from vigilia.core.types import Action, HeldState, InputEdge, RayHit, VolumeRayHit
from vigilia.core.views import VitalsView, BossView, StatusView, StatsView, ItemView, EquipmentView, ItemCategory, UICommand, Color, Rect
from vigilia.core.views import SlotView, SlotDeletionView, CharacterClassView, OptionView, MapRegionView, MapMarkerView


class ISaveSlotsQuery(Protocol):
    def slots(self) -> list[SlotView]: ...
    def slot_deletion(self, slot: int) -> SlotDeletionView: ...
    def slot_in_use(self, slot: int) -> bool: ...


class ICharacterClassesQuery(Protocol):
    def character_classes(self) -> tuple[CharacterClassView, ...]: ...


class ISettingsQuery(Protocol):
    def option_rows(self, category: str) -> tuple[OptionView, ...]: ...
    def binding_conflicts(self, action: str, binding: str) -> tuple[str, ...]: ...


class ICombatHUDQuery(Protocol):
    def player_vitals(self) -> VitalsView: ...
    def active_boss(self) -> BossView | None: ...
    def active_statuses(self) -> list[StatusView]: ...


class IStatsQuery(Protocol):
    def current(self) -> StatsView: ...
    def preview(self, attribute: str) -> StatsView: ...
    def next_level_cost(self) -> int: ...


class IInventoryQuery(Protocol):
    def items_by_category(self, category: ItemCategory) -> list[ItemView]: ...
    def equipped(self) -> EquipmentView: ...


class IUIActions(Protocol):
    def execute(self, command: UICommand) -> str: ...


class IMenuInput(Protocol):
    def menu_next_edge(self) -> InputEdge | None: ...
    def menu_held(self) -> HeldState: ...
    def begin_binding_capture(self, device: str = "keyboard") -> None: ...
    def captured_binding(self) -> str | None: ...


class IUIBackend(Protocol):
    def t(self, key: str, **values) -> str: ...
    def create(self, key: str, kind: str, rect: Rect, *, parent: str | None = None,
               text: str = "", size: int = 20, color: Color = (1, 1, 1, 1),
               command: Callable[..., None] | None = None, value: float = 0.,
               minimum: float = 0., maximum: float = 1.) -> None: ...
    def text(self, key: str, value: str) -> None: ...
    def visible(self, key: str, value: bool) -> None: ...
    def fraction(self, key: str, value: float) -> None: ...
    def color(self, key: str, value: Color) -> None: ...
    def enabled(self, key: str, value: bool) -> None: ...
    def destroy(self, key: str) -> None: ...
    def read_text(self, key: str) -> str: ...
    def focus_text(self, key: str, value: bool) -> None: ...
    def text_active(self) -> bool: ...
    def scale_at(self, key: str, value: float, anchor: str) -> None: ...


class IInputSource(Protocol):
    def next_edge(self) -> InputEdge | None: ...
    def held(self) -> HeldState: ...
    def rebind(self, action: Action, binding: str) -> None: ...


class IAudioBackend(Protocol):
    def play_sfx(self, clip_id: str, *, position: Vec3 | None = None,
                 priority: int = 1, gain: float = 1) -> bool: ...
    def play_music(self, track_id: str, *, fade_sec: float = 1.5) -> None: ...
    def stop_music(self, *, fade_sec: float = 1.) -> None: ...


class IPhysicsWorld(Protocol):
    def step(self, dt: float) -> None: ...
    def raycast(self, origin: Vec3, end: Vec3) -> RayHit | None: ...
    def sweep_sphere(self, origin: Vec3, end: Vec3, radius: float) -> RayHit | None: ...


class ICharacterBody(Protocol):
    def set_velocity(self, velocity: Vec3) -> None: ...
    def position(self) -> Vec3: ...
    def teleport(self, position: Vec3) -> None: ...
    def set_active(self, active: bool) -> None: ...


class IAgileBody(ICharacterBody, Protocol):
    crouched: bool
    def set_crouched(self, enabled: bool) -> bool: ...
    def grounded(self) -> bool: ...
    def jump(self, speed: float) -> bool: ...


class IObstacle(Protocol):
    def set_active(self, active: bool) -> None: ...


class IContactVolumes(Protocol):
    def sync(self, volumes: dict[tuple[int, str], tuple[Vec3, float]]) -> None: ...
    def overlaps(self, source: tuple[int, str], targets: Sequence[tuple[int, str]]) -> bool: ...
    def raycast(self, origin: Vec3, end: Vec3,
                targets: Sequence[tuple[int, str]]) -> VolumeRayHit | None: ...


@runtime_checkable
class IMapDataProvider(Protocol):
    def discovered_areas(self) -> tuple[str, ...]: ...
    def discovered_bonfires(self) -> tuple[str, ...]: ...
    def player_position(self) -> Vec3: ...
    def regions(self) -> tuple[MapRegionView, ...]: ...
    def bonfires(self) -> tuple[MapMarkerView, ...]: ...
