"""Mede três cabeçalhos por leitura, em cópia SQLite da fixture sintética."""

import argparse
from contextlib import closing
import json
import math
from pathlib import Path
import sqlite3
import statistics
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from vigilia.save.service import SaveService


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--samples", type=int, default=2000)
    parser.add_argument("--source", type=Path, default=ROOT / "artifacts/5.2a/fixture-v3.sqlite3")
    parser.add_argument("--output", type=Path, default=ROOT / "artifacts/5.2b/headers.json")
    args = parser.parse_args()
    if args.samples < 1000:
        parser.error("Use pelo menos 1000 amostras.")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    target = args.output.parent / "headers-fixture.sqlite3"
    if target.resolve() == args.source.resolve():
        parser.error("A origem deve ser preservada.")
    with closing(sqlite3.connect(args.source)) as source, closing(sqlite3.connect(target)) as destination:
        source.backup(destination)
    service = SaveService(target)
    for _ in range(50):
        assert all(row.occupied for row in service.list_slots())
    samples = []
    for _ in range(args.samples):
        start = time.perf_counter_ns()
        rows = service.list_slots()
        samples.append((time.perf_counter_ns() - start) / 1e6)
        assert len(rows) == 3 and all(row.occupied for row in rows)
    ordered = sorted(samples)
    percentile = lambda p: ordered[math.ceil(p * len(ordered)) - 1]
    report = dict(samples=len(samples), headers_per_read=3, warmup_reads=50, percentile_method="nearest rank",
        source_kind="synthetic fixture generated by native QA; no player-provided database",
        source=str(args.source.relative_to(ROOT)), unit="ms", median=statistics.median(samples),
        p95=percentile(.95), p99=percentile(.99), maximum=max(samples), mean=statistics.mean(samples),
        p99_budget_ms=5, p99_within_budget=percentile(.99) <= 5, samples_ms=samples)
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({key:value for key,value in report.items() if key != "samples_ms"}, ensure_ascii=False))


if __name__ == "__main__":
    main()
